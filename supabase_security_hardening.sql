-- Apply in SQL Editor ONLY after both deployed servers use service_role.
-- This changes access controls, not application rows or credentials.
begin;

create table if not exists public.broadcast_log (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  platform text not null,
  currency_ids text not null,
  status text not null,
  attempts integer not null default 1,
  duration_ms integer,
  error_message text,
  is_test integer not null default 0
);

do $$
declare
  target_table text;
  sequence_name text;
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'broadcast_log'
      and column_name = 'created_at' and data_type = 'timestamp with time zone'
  ) then
    raise exception 'broadcast_log.created_at must be timestamptz; review existing schema before continuing';
  end if;

  foreach target_table in array array[
    'app_config', 'server_config', 'push_subscriptions', 'visitor_messages',
    'visitor_logs', 'analytics_events', 'installs', 'telegram_visits',
    'error_logs', 'broadcast_state', 'broadcast_log', 'price_changes_log',
    'parallel_rates', 'official_rates', 'metal_rates', 'exchange_rates'
  ] loop
    if to_regclass(format('public.%I', target_table)) is null then
      raise exception 'Required table missing: %', target_table;
    end if;
    execute format('alter table public.%I enable row level security', target_table);
    execute format('revoke all privileges on table public.%I from public, anon, authenticated', target_table);
    execute format('grant select, insert, update, delete on table public.%I to service_role', target_table);
    sequence_name := null;
    if exists (select 1 from information_schema.columns where table_schema = 'public'
      and table_name = target_table and column_name = 'id') then
      sequence_name := pg_get_serial_sequence(format('public.%I', target_table), 'id');
    end if;
    if sequence_name is not null then
      execute format('revoke all privileges on sequence %s from public, anon, authenticated', sequence_name);
      execute format('grant usage, select on sequence %s to service_role', sequence_name);
    end if;
  end loop;
end $$;

create index if not exists idx_broadcast_log_created_at on public.broadcast_log(created_at);

revoke all privileges on function public.increment_telegram_visits(text, text, text)
  from public, anon, authenticated;
grant execute on function public.increment_telegram_visits(text, text, text) to service_role;

notify pgrst, 'reload schema';
commit;

-- Expected: RLS true; all browser privileges false; Worker/Web read and write true.
select c.relname as table_name, c.relrowsecurity as rls_enabled,
  has_table_privilege('anon', c.oid, 'SELECT,INSERT,UPDATE,DELETE') as anon_has_access,
  has_table_privilege('authenticated', c.oid, 'SELECT,INSERT,UPDATE,DELETE') as authenticated_has_access,
  has_table_privilege('service_role', c.oid, 'SELECT') as server_can_read,
  has_table_privilege('service_role', c.oid, 'INSERT') as server_can_insert
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind = 'r'
order by c.relname;
